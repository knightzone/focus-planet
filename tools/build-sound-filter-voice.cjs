// 声音过滤器：生成「类型播报」语音。
//
// 语音 = edge-tts 晓晓声线（与结算语音同一人声），文案取自 utils/sound-filter.uts 的类型表，
// 一句一类（例如「找一找，动物」）。生成后写入 static/audio/sound-filter/<类型>.mp3，
// 同时刷新 utils/sound-filter-voice.uts —— 页面只播这里有登记的录音，没登记时显示文字兜底。
//
// 用法：
//   node tools/build-sound-filter-voice.cjs            # 只补缺失的
//   node tools/build-sound-filter-voice.cjs --force    # 全部重生成
//   EDGE_TTS_CLI=/path/to/edge-tts node tools/build-sound-filter-voice.cjs
// 依赖：edge-tts（pip3 install --user --break-system-packages edge-tts）、ffmpeg。

const fs = require('node:fs')
const path = require('node:path')
const os = require('node:os')
const cp = require('node:child_process')

const root = path.resolve(__dirname, '..')
const source = path.join(root, 'utils/sound-filter.uts')
const runtime = path.join(root, 'static/audio/sound-filter')
const manifest = path.join(root, 'utils/sound-filter-voice.uts')
const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'sound-filter-voice-'))
const force = process.argv.includes('--force')
const voice = process.env.EDGE_TTS_VOICE || 'zh-CN-XiaoxiaoNeural'
const cliCandidates = [
  process.env.EDGE_TTS_CLI,
  path.join(os.homedir(), 'Library/Python/3.13/bin/edge-tts'),
  '/private/tmp/focus-natural-voice-env/bin/edge-tts',
  '/usr/local/bin/edge-tts'
].filter(Boolean)

function pickCli() {
  for (const candidate of cliCandidates) {
    if (fs.existsSync(candidate)) return candidate
  }
  throw new Error(`找不到 edge-tts，可用 EDGE_TTS_CLI 指定。已尝试：${cliCandidates.join('、')}`)
}

function readTypes() {
  let text
  try {
    text = fs.readFileSync(source, 'utf8')
  } catch (error) {
    throw new Error(`读不到类型表 ${source}：${error.message}`)
  }
  const found = []
  // 类型表的条目可能跨多行（id / label / assets 分行写），所以不绑定行首的大括号。
  const pattern = /id: '([a-z]+)', label: '([^']+)', assets:/g
  let match = pattern.exec(text)
  while (match != null) {
    found.push({ id: match[1], label: match[2] })
    match = pattern.exec(text)
  }
  if (found.length == 0) throw new Error('类型表解析失败：utils/sound-filter.uts 里没找到 id / label / assets 结构')
  return found
}

function synthesize(cli, text, file) {
  const raw = path.join(tmp, 'raw.mp3')
  try {
    cp.execFileSync(cli, ['--voice', voice, '--rate=-8%', '--text', text, '--write-media', raw], { timeout: 60000, stdio: 'inherit' })
  } catch (error) {
    throw new Error(`edge-tts 合成失败（${text}）：${error.message}`)
  }
  try {
    cp.execFileSync('/usr/local/bin/ffmpeg', ['-y', '-v', 'error', '-i', raw, '-af', 'loudnorm=I=-21:TP=-3:LRA=7', '-ar', '24000', '-ac', '1', '-c:a', 'libmp3lame', '-b:a', '64k', file], { timeout: 20000, stdio: 'inherit' })
  } catch (error) {
    throw new Error(`ffmpeg 转码失败（${file}）：${error.message}`)
  }
}

const types = readTypes()
fs.mkdirSync(runtime, { recursive: true })
const cli = pickCli()
const built = []
for (const type of types) {
  const file = path.join(runtime, `${type.id}.mp3`)
  const text = `找一找，${type.label}`
  if (force || !fs.existsSync(file)) {
    synthesize(cli, text, file)
    built.push(type.id)
    console.log(`✔ ${type.id}.mp3  「${text}」`)
  }
}

const files = types.filter((type) => fs.existsSync(path.join(runtime, `${type.id}.mp3`))).map((type) => `/static/audio/sound-filter/${type.id}.mp3`)
fs.writeFileSync(
  manifest,
  '// Generated by tools/build-sound-filter-voice.cjs：可用的类型播报录音列表。\n'
  + '// 没登记的类型，页面只显示文字（语音未生成时不影响玩法）。\n'
  + 'export const SOUND_FILTER_VOICE_FILES: string[] = [\n'
  + files.map((file) => `  '${file}'`).join(',\n')
  + '\n]\n'
)
fs.rmSync(tmp, { recursive: true, force: true })
console.log(JSON.stringify({ types: types.length, generated: built.length, missing: types.length - files.length, manifest: 'utils/sound-filter-voice.uts' }))
