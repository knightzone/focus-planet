// 一心二用小司机：生成「训练开始时」的玩法语音。
//
// 一句：「跃跃、暖暖把头伸出车窗很危险，点一下他们，让他们坐好」——
// 在正式训练开始时播报，说明底部滚动条要做什么（点到探头的小朋友 = 提醒他坐好）。
// 语音 = edge-tts 晓晓声线（与结算语音同一人声）。生成后写入 static/audio/little-driver/<id>.mp3，
// 同时刷新 utils/little-driver-voice.uts —— 页面只播这里有登记的录音；没登记时只显示文字。
//
// 用法：
//   node tools/build-little-driver-voice.cjs            # 只补缺失的
//   node tools/build-little-driver-voice.cjs --force    # 全部重生成
//   EDGE_TTS_CLI=/path/to/edge-tts node tools/build-little-driver-voice.cjs
// 依赖：edge-tts（pip3 install --user --break-system-packages edge-tts）、ffmpeg / ffprobe。

const fs = require('node:fs')
const path = require('node:path')
const os = require('node:os')
const cp = require('node:child_process')

const root = path.resolve(__dirname, '..')
const runtime = path.join(root, 'static/audio/little-driver')
const manifest = path.join(root, 'utils/little-driver-voice.uts')
const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'little-driver-voice-'))
const force = process.argv.includes('--force')
const voice = process.env.EDGE_TTS_VOICE || 'zh-CN-XiaoxiaoNeural'

const LINES = [
  { id: 'safety-intro', text: '跃跃、暖暖把头伸出车窗很危险，点一下他们，让他们坐好' }
]

const cliCandidates = [
  process.env.EDGE_TTS_CLI,
  path.join(os.homedir(), 'Library/Python/3.13/bin/edge-tts'),
  '/private/tmp/focus-natural-voice-env/bin/edge-tts',
  '/usr/local/bin/edge-tts'
].filter(Boolean)

function pickCli() {
  for (const candidate of cliCandidates) {
    if (fs.existsSync(candidate)) return candidate
  }
  throw new Error(`找不到 edge-tts，可用 EDGE_TTS_CLI 指定。已尝试：${cliCandidates.join('、')}`)
}

function durationMs(file) {
  let output
  try {
    output = cp.execFileSync('/usr/local/bin/ffprobe', ['-v', 'error', '-show_entries', 'format=duration', '-of', 'default=noprint_wrappers=1:nokey=1', file], { timeout: 20000 })
  } catch (error) {
    throw new Error(`ffprobe 读时长失败（${file}）：${error.message}`)
  }
  const seconds = parseFloat(String(output).trim())
  if (!Number.isFinite(seconds) || seconds <= 0) throw new Error(`读不到有效时长：${file}`)
  return Math.round(seconds * 1000)
}

function synthesize(cli, text, file) {
  const raw = path.join(tmp, 'raw.mp3')
  try {
    cp.execFileSync(cli, ['--voice', voice, '--rate=-8%', '--text', text, '--write-media', raw], { timeout: 60000, stdio: 'inherit' })
  } catch (error) {
    throw new Error(`edge-tts 合成失败（${text}）：${error.message}`)
  }
  try {
    cp.execFileSync('/usr/local/bin/ffmpeg', ['-y', '-v', 'error', '-i', raw, '-af', 'loudnorm=I=-21:TP=-3:LRA=7', '-ar', '24000', '-ac', '1', '-c:a', 'libmp3lame', '-b:a', '64k', file], { timeout: 20000, stdio: 'inherit' })
  } catch (error) {
    throw new Error(`ffmpeg 转码失败（${file}）：${error.message}`)
  }
}

fs.mkdirSync(runtime, { recursive: true })
const cli = pickCli()
const built = []
const kept = []
for (const line of LINES) {
  const file = path.join(runtime, `${line.id}.mp3`)
  if (force || !fs.existsSync(file)) {
    synthesize(cli, line.text, file)
    built.push(line.id)
    console.log(`✔ ${line.id}.mp3  「${line.text}」`)
  } else {
    kept.push(line.id)
  }
}

const available = LINES.filter((line) => fs.existsSync(path.join(runtime, `${line.id}.mp3`)))
fs.writeFileSync(
  manifest,
  '// Generated by tools/build-little-driver-voice.cjs：训练开始时的玩法语音。\n'
  + '// 没登记的条目，页面只显示文字（语音未生成时不影响玩法）。\n'
  + 'export const LITTLE_DRIVER_VOICE_IDS: string[] = [\n'
  + available.map((line) => `  '${line.id}'`).join(',\n')
  + '\n]\n'
  + 'export const LITTLE_DRIVER_VOICE_FILES: string[] = [\n'
  + available.map((line) => `  '/static/audio/little-driver/${line.id}.mp3'`).join(',\n')
  + '\n]\n'
  + 'export const LITTLE_DRIVER_VOICE_TEXTS: string[] = [\n'
  + available.map((line) => `  '${line.text}'`).join(',\n')
  + '\n]\n'
  + 'export const LITTLE_DRIVER_VOICE_MS: number[] = [\n'
  + available.map((line) => `  ${durationMs(path.join(runtime, `${line.id}.mp3`))}`).join(',\n')
  + '\n]\n'
)
fs.rmSync(tmp, { recursive: true, force: true })
console.log(JSON.stringify({ lines: LINES.length, generated: built.length, reused: kept.length, missing: LINES.length - available.length, manifest: 'utils/little-driver-voice.uts' }))
