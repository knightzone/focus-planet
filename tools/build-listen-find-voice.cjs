// 听声捉图形：生成指令语音（按部件拼接）。
//
// 部件 12 个：点击 / 左侧 / 右侧 / 上方 / 下方 / 圆形 / 方形 / 三角形 / 红色图形 / 黄色图形 / 绿色图形 / 蓝色图形
// 指令 = 点击 + 半屏 + 描述符，4 × 7 = 28 句，例如「点击左侧方形」「点击下方红色图形」。
//
// 拼接在**构建期**完成：每个部件先合成、去首尾静音、统一响度，再用 ffmpeg concat 拼成整句，
// 运行时一句一个文件、不用在页面上串接音频（避免播放间隙）。
// 语音 = edge-tts 晓晓声线（与结算语音同一人声）。
//
// 用法：
//   node tools/build-listen-find-voice.cjs           # 只补缺失的
//   node tools/build-listen-find-voice.cjs --force   # 全部重生成
//   EDGE_TTS_CLI=/path/to/edge-tts node tools/build-listen-find-voice.cjs
// 依赖：edge-tts（pip3 install --user --break-system-packages edge-tts）、ffmpeg / ffprobe。

const fs = require('node:fs')
const path = require('node:path')
const os = require('node:os')
const cp = require('node:child_process')

const root = path.resolve(__dirname, '..')
const runtime = path.join(root, 'static/audio/listen-find')
const manifest = path.join(root, 'utils/listen-find-voice.uts')
const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'listen-find-voice-'))
const force = process.argv.includes('--force')
const voice = process.env.EDGE_TTS_VOICE || 'zh-CN-XiaoxiaoNeural'

// 部件：id → 文本。点击 + 半屏 + 描述符 三段拼一句。
const PARTS = {
  tap: '点击',
  left: '左侧',
  right: '右侧',
  top: '上方',
  bottom: '下方',
  circle: '圆形',
  square: '方形',
  triangle: '三角形',
  red: '红色图形',
  yellow: '黄色图形',
  green: '绿色图形',
  blue: '蓝色图形'
}
const HALVES = ['left', 'right', 'top', 'bottom']
const DESCRIPTORS = ['circle', 'square', 'triangle', 'red', 'yellow', 'green', 'blue']
const PART_ORDER = ['tap', ...HALVES, 'circle', 'square', 'triangle', 'red', 'yellow', 'green', 'blue']

const cliCandidates = [
  process.env.EDGE_TTS_CLI,
  path.join(os.homedir(), 'Library/Python/3.13/bin/edge-tts'),
  '/private/tmp/focus-natural-voice-env/bin/edge-tts',
  '/usr/local/bin/edge-tts'
].filter(Boolean)

function pickCli() {
  for (const candidate of cliCandidates) {
    if (fs.existsSync(candidate)) return candidate
  }
  throw new Error(`找不到 edge-tts，可用 EDGE_TTS_CLI 指定。已尝试：${cliCandidates.join('、')}`)
}

function durationMs(file) {
  let output
  try {
    output = cp.execFileSync('/usr/local/bin/ffprobe', ['-v', 'error', '-show_entries', 'format=duration', '-of', 'default=noprint_wrappers=1:nokey=1', file], { timeout: 20000 })
  } catch (error) {
    throw new Error(`ffprobe 读时长失败（${file}）：${error.message}`)
  }
  const seconds = parseFloat(String(output).trim())
  if (!Number.isFinite(seconds) || seconds <= 0) throw new Error(`读不到有效时长：${file}`)
  return Math.round(seconds * 1000)
}

// 去首尾静音 + 统一响度（-21 LUFS），24kHz 单声道 64k —— 与其它语音素材同一口径。
const CLEAN_FILTER = [
  'silenceremove=start_periods=1:start_silence=0.03:start_threshold=-40dB',
  'areverse',
  'silenceremove=start_periods=1:start_silence=0.03:start_threshold=-40dB',
  'areverse',
  'loudnorm=I=-21:TP=-3:LRA=7'
].join(',')

function synthesizePart(cli, id, text) {
  const raw = path.join(tmp, `raw-${id}.mp3`)
  const clean = path.join(tmp, `clean-${id}.mp3`)
  try {
    cp.execFileSync(cli, ['--voice', voice, '--rate=-8%', '--text', text, '--write-media', raw], { timeout: 60000, stdio: 'inherit' })
  } catch (error) {
    throw new Error(`edge-tts 合成失败（${text}）：${error.message}`)
  }
  try {
    cp.execFileSync('/usr/local/bin/ffmpeg', ['-y', '-v', 'error', '-i', raw, '-af', CLEAN_FILTER, '-ar', '24000', '-ac', '1', '-c:a', 'libmp3lame', '-b:a', '64k', clean], { timeout: 20000, stdio: 'inherit' })
  } catch (error) {
    throw new Error(`部件清理失败（${id}）：${error.message}`)
  }
  return clean
}

function concatParts(files, output) {
  const args = ['-y', '-v', 'error']
  for (const file of files) args.push('-i', file)
  const inputs = files.map((_, index) => `[${index}:a]`).join('')
  args.push('-filter_complex', `${inputs}concat=n=${files.length}:v=0:a=1,aresample=24000[out]`, '-map', '[out]', '-ac', '1', '-c:a', 'libmp3lame', '-b:a', '64k', output)
  try {
    cp.execFileSync('/usr/local/bin/ffmpeg', args, { timeout: 30000 })
  } catch (error) {
    throw new Error(`拼接失败（${output}）：${error.message}`)
  }
}

fs.mkdirSync(runtime, { recursive: true })
const cli = pickCli()
const cleaned = new Map()
for (const id of PART_ORDER) {
  cleaned.set(id, synthesizePart(cli, id, PARTS[id]))
  console.log(`• 部件 ${id} 「${PARTS[id]}」`)
}

const entries = []
for (const half of HALVES) {
  for (const descriptor of DESCRIPTORS) {
    const id = `${half}-${descriptor}`
    const text = PARTS.tap + PARTS[half] + PARTS[descriptor]
    const file = path.join(runtime, `${id}.mp3`)
    if (force || !fs.existsSync(file)) {
      concatParts([cleaned.get('tap'), cleaned.get(half), cleaned.get(descriptor)], file)
      console.log(`✔ ${id}.mp3  「${text}」`)
    }
    entries.push({ id, text, file: `/static/audio/listen-find/${id}.mp3`, ms: durationMs(file) })
  }
}

fs.writeFileSync(
  manifest,
  '// Generated by tools/build-listen-find-voice.cjs：指令语音（按部件拼接）。\n'
  + '// 一句一个文件；页面按 id 找文件，找不到就只显示文字（语音缺失不影响玩法）。\n'
  + 'export const LISTEN_FIND_VOICE_IDS: string[] = [\n'
  + entries.map((entry) => `  '${entry.id}'`).join(',\n')
  + '\n]\n'
  + 'export const LISTEN_FIND_VOICE_FILES: string[] = [\n'
  + entries.map((entry) => `  '${entry.file}'`).join(',\n')
  + '\n]\n'
  + 'export const LISTEN_FIND_VOICE_TEXTS: string[] = [\n'
  + entries.map((entry) => `  '${entry.text}'`).join(',\n')
  + '\n]\n'
  + 'export const LISTEN_FIND_VOICE_MS: number[] = [\n'
  + entries.map((entry) => `  ${entry.ms}`).join(',\n')
  + '\n]\n'
)
fs.rmSync(tmp, { recursive: true, force: true })
const totalMs = entries.reduce((sum, entry) => sum + entry.ms, 0)
console.log(JSON.stringify({ parts: PART_ORDER.length, phrases: entries.length, shortestMs: Math.min(...entries.map((entry) => entry.ms)), longestMs: Math.max(...entries.map((entry) => entry.ms)), totalMs: totalMs, manifest: 'utils/listen-find-voice.uts' }))
