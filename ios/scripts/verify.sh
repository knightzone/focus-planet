#!/usr/bin/env bash
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
IOS_DIR="$(cd "$SCRIPT_DIR/.." && pwd)"
APP_ID="__UNI__B5780B0"
EXPECTED_RUNTIME_VERSION="5.26"
resource_manifest="$IOS_DIR/FocusPlanet/FocusPlanet/uni-app-x/apps/$APP_ID/www/manifest.json"

command -v xcodebuild >/dev/null || { echo "Xcode command-line tools are missing." >&2; exit 1; }
[[ -d "$IOS_DIR/SDK/Libs/DCloudUniappRuntime.xcframework" ]] || { echo "Missing SDK; run install-sdk.sh." >&2; exit 1; }
[[ -d "$IOS_DIR/CustomFrameworks/DCloudUTSExtAPI.xcframework" ]] || { echo "Missing custom DCloudUTSExtAPI; run build-extapi.sh." >&2; exit 1; }
[[ -f "$resource_manifest" ]] || { echo "Missing exported $APP_ID app resources; run sync-resources.sh." >&2; exit 1; }
[[ "$(cat "$IOS_DIR/SDK/.uniappx-sdk-version" 2>/dev/null || true)" == "$EXPECTED_RUNTIME_VERSION" ]] || { echo "Expected uni-app x iOS SDK $EXPECTED_RUNTIME_VERSION; run install-sdk.sh." >&2; exit 1; }
[[ "$(plutil -extract 'uni-app-x.compilerVersion' raw -o - "$resource_manifest" 2>/dev/null || true)" == "$EXPECTED_RUNTIME_VERSION" ]] || { echo "App resources were not generated by HBuilderX $EXPECTED_RUNTIME_VERSION; regenerate and sync them." >&2; exit 1; }
[[ "$(plutil -extract 'uniapp-x.uniRuntimeVersion' raw -o - "$IOS_DIR/FocusPlanet/FocusPlanet/Info.plist" 2>/dev/null || true)" == "$EXPECTED_RUNTIME_VERSION" ]] || { echo "Info.plist runtime version must be $EXPECTED_RUNTIME_VERSION." >&2; exit 1; }
plugin_framework="$IOS_DIR/Plugins/unimoduleFocusFaceDetector.xcframework"
[[ -f "$plugin_framework/ios-arm64/unimoduleFocusFaceDetector.framework/unimoduleFocusFaceDetector" ]] || { echo "Missing face detector device slice; run build-plugin.sh." >&2; exit 1; }
native_source="$IOS_DIR/../uni_modules/focus-face-detector/utssdk/app-ios/FocusFaceDetectorNative.swift"
plugin_native_source="$IOS_DIR/Plugins/Source/unimoduleFocusFaceDetector/unimoduleFocusFaceDetector/FocusFaceDetectorNative.swift"
plugin_binary="$plugin_framework/ios-arm64/unimoduleFocusFaceDetector.framework/unimoduleFocusFaceDetector"
cmp -s "$native_source" "$plugin_native_source" || { echo "iOS native plugin source is not synchronized; run sync-resources.sh." >&2; exit 1; }
[[ ! "$native_source" -nt "$plugin_binary" ]] || { echo "iOS native plugin binary is stale; run build-plugin.sh." >&2; exit 1; }
if [[ -f "$plugin_framework/ios-arm64_x86_64-simulator/unimoduleFocusFaceDetector.framework/unimoduleFocusFaceDetector" ]]; then
  simulator_slice="$plugin_framework/ios-arm64_x86_64-simulator/unimoduleFocusFaceDetector.framework/unimoduleFocusFaceDetector"
elif [[ -f "$plugin_framework/ios-arm64-simulator/unimoduleFocusFaceDetector.framework/unimoduleFocusFaceDetector" ]]; then
  simulator_slice="$plugin_framework/ios-arm64-simulator/unimoduleFocusFaceDetector.framework/unimoduleFocusFaceDetector"
else
  echo "Missing face detector simulator slice; run build-plugin.sh (模拟器会因 'incompatible platform' 闪退)." >&2
  exit 1
fi
[[ "$(vtool -show-build "$simulator_slice" 2>/dev/null | awk '/platform/ {print $2; exit}')" == "IOSSIMULATOR" ]] || { echo "Face detector simulator slice is not built for the simulator platform." >&2; exit 1; }

if rg -q 'INFOPLIST_KEY_UI(Main|Launch)Storyboard' "$IOS_DIR/FocusPlanet/FocusPlanet.xcodeproj/project.pbxproj"; then
  echo "The host declares a storyboard that is not bundled; remove the generated storyboard build settings." >&2
  exit 1
fi

if nm -gj "$plugin_framework/ios-arm64/unimoduleFocusFaceDetector.framework/unimoduleFocusFaceDetector" | rg -q 'OBJC_CLASS_\$_(UTSOC|DCloudUTSConfig)'; then
  echo "The face detector contains duplicate UTS bootstrap classes; rebuild it without UTSOC.mm." >&2
  exit 1
fi
# 首页渐变已改为静态 SVG，不再要求原生渐变类；端侧检测仍保留完整校验。

plist_appid="$(/usr/libexec/PlistBuddy -c 'Print :uniapp-x:appid' "$IOS_DIR/FocusPlanet/FocusPlanet/Info.plist")"
[[ "$plist_appid" == "$APP_ID" ]] || { echo "Info.plist appid mismatch: $plist_appid" >&2; exit 1; }

"$SCRIPT_DIR/check-resource-freshness.sh"
xcodebuild -list -project "$IOS_DIR/FocusPlanet/FocusPlanet.xcodeproj" >/dev/null
echo "Xcode local-packaging inputs are ready."
