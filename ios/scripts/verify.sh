#!/usr/bin/env bash
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
IOS_DIR="$(cd "$SCRIPT_DIR/.." && pwd)"
APP_ID="__UNI__B5780B0"
EXPECTED_RUNTIME_VERSION="5.26"
resource_manifest="$IOS_DIR/FocusPlanet/FocusPlanet/uni-app-x/apps/$APP_ID/www/manifest.json"

command -v xcodebuild >/dev/null || { echo "Xcode command-line tools are missing." >&2; exit 1; }
[[ -d "$IOS_DIR/SDK/Libs/DCloudUniappRuntime.xcframework" ]] || { echo "Missing SDK; run install-sdk.sh." >&2; exit 1; }
[[ -d "$IOS_DIR/CustomFrameworks/DCloudUTSExtAPI.xcframework" ]] || { echo "Missing custom DCloudUTSExtAPI; run build-extapi.sh." >&2; exit 1; }
[[ -f "$resource_manifest" ]] || { echo "Missing exported $APP_ID app resources; run sync-resources.sh." >&2; exit 1; }
[[ "$(cat "$IOS_DIR/SDK/.uniappx-sdk-version" 2>/dev/null || true)" == "$EXPECTED_RUNTIME_VERSION" ]] || { echo "Expected uni-app x iOS SDK $EXPECTED_RUNTIME_VERSION; run install-sdk.sh." >&2; exit 1; }
[[ "$(plutil -extract 'uni-app-x.compilerVersion' raw -o - "$resource_manifest" 2>/dev/null || true)" == "$EXPECTED_RUNTIME_VERSION" ]] || { echo "App resources were not generated by HBuilderX $EXPECTED_RUNTIME_VERSION; regenerate and sync them." >&2; exit 1; }
[[ "$(plutil -extract 'uniapp-x.uniRuntimeVersion' raw -o - "$IOS_DIR/FocusPlanet/FocusPlanet/Info.plist" 2>/dev/null || true)" == "$EXPECTED_RUNTIME_VERSION" ]] || { echo "Info.plist runtime version must be $EXPECTED_RUNTIME_VERSION." >&2; exit 1; }

# 版本号三处必须一致：manifest.json（JS 的 appVersion / versionCode）、Xcode 的
# MARKETING_VERSION / CURRENT_PROJECT_VERSION、HBuilderX 导出的资源 manifest。
# 不一致会让服务端版本回显对不上、更新提示静默失效，构前先拦。
PROJECT_ROOT="$(cd "$IOS_DIR/.." && pwd)"
pbx="$IOS_DIR/FocusPlanet/FocusPlanet.xcodeproj/project.pbxproj"
src_version_name="$(plutil -extract versionName raw -o - "$PROJECT_ROOT/manifest.json" 2>/dev/null || true)"
src_version_code="$(plutil -extract versionCode raw -o - "$PROJECT_ROOT/manifest.json" 2>/dev/null || true)"
out_version_name="$(plutil -extract 'version.name' raw -o - "$resource_manifest" 2>/dev/null || true)"
out_version_code="$(plutil -extract 'version.code' raw -o - "$resource_manifest" 2>/dev/null || true)"
xcode_version_name="$(rg -o 'MARKETING_VERSION = [0-9][0-9.]*' "$pbx" | sed 's/.*= //' | sort -u | paste -sd, - || true)"
xcode_version_code="$(rg -o 'CURRENT_PROJECT_VERSION = [0-9][0-9]*' "$pbx" | sed 's/.*= //' | sort -u | paste -sd, - || true)"
if [[ -z "$src_version_name" || "$out_version_name" != "$src_version_name" || "$out_version_code" != "$src_version_code" || "$xcode_version_name" != "$src_version_name" || "$xcode_version_code" != "$src_version_code" ]]; then
  echo "Version mismatch: manifest.json ${src_version_name}(${src_version_code}), bundle ${out_version_name}(${out_version_code}), Xcode ${xcode_version_name}(${xcode_version_code})." >&2
  exit 1
fi
plugin_framework="$IOS_DIR/Plugins/unimoduleFocusFaceDetector.xcframework"
[[ -f "$plugin_framework/ios-arm64/unimoduleFocusFaceDetector.framework/unimoduleFocusFaceDetector" ]] || { echo "Missing face detector device slice; run build-plugin.sh." >&2; exit 1; }
native_source="$IOS_DIR/../uni_modules/focus-face-detector/utssdk/app-ios/FocusFaceDetectorNative.swift"
plugin_native_source="$IOS_DIR/Plugins/Source/unimoduleFocusFaceDetector/unimoduleFocusFaceDetector/FocusFaceDetectorNative.swift"
plugin_binary="$plugin_framework/ios-arm64/unimoduleFocusFaceDetector.framework/unimoduleFocusFaceDetector"
cmp -s "$native_source" "$plugin_native_source" || { echo "iOS native plugin source is not synchronized; run sync-resources.sh." >&2; exit 1; }
[[ ! "$native_source" -nt "$plugin_binary" ]] || { echo "iOS native plugin binary is stale; run build-plugin.sh." >&2; exit 1; }
if [[ -f "$plugin_framework/ios-arm64_x86_64-simulator/unimoduleFocusFaceDetector.framework/unimoduleFocusFaceDetector" ]]; then
  simulator_slice="$plugin_framework/ios-arm64_x86_64-simulator/unimoduleFocusFaceDetector.framework/unimoduleFocusFaceDetector"
elif [[ -f "$plugin_framework/ios-arm64-simulator/unimoduleFocusFaceDetector.framework/unimoduleFocusFaceDetector" ]]; then
  simulator_slice="$plugin_framework/ios-arm64-simulator/unimoduleFocusFaceDetector.framework/unimoduleFocusFaceDetector"
else
  echo "Missing face detector simulator slice; run build-plugin.sh (模拟器会因 'incompatible platform' 闪退)." >&2
  exit 1
fi
[[ "$(vtool -show-build "$simulator_slice" 2>/dev/null | awk '/platform/ {print $2; exit}')" == "IOSSIMULATOR" ]] || { echo "Face detector simulator slice is not built for the simulator platform." >&2; exit 1; }

if rg -q 'INFOPLIST_KEY_UI(Main|Launch)Storyboard' "$IOS_DIR/FocusPlanet/FocusPlanet.xcodeproj/project.pbxproj"; then
  echo "The host declares a storyboard that is not bundled; remove the generated storyboard build settings." >&2
  exit 1
fi

# 权限文案：模板残留的 INFOPLIST_KEY_NS* 会把通讯录/健康/位置/追踪等用不到的权限带进包；
# 竖屏也不允许再出现 iPhone/iPad 的横屏变体。
if rg -q 'INFOPLIST_KEY_NS[A-Za-z]+UsageDescription' "$IOS_DIR/FocusPlanet/FocusPlanet.xcodeproj/project.pbxproj"; then
  echo "Template INFOPLIST_KEY_NS* usage descriptions are back; keep permissions empty." >&2
  exit 1
fi
if rg -q 'INFOPLIST_KEY_UISupportedInterfaceOrientations(_iPad|_iPhone)' "$IOS_DIR/FocusPlanet/FocusPlanet.xcodeproj/project.pbxproj"; then
  echo "iPhone/iPad orientation variants re-enable landscape; keep UISupportedInterfaceOrientations portrait-only." >&2
  exit 1
fi

# 2026-10-15 本版本不支持摄像头/相册：宿主不能声明相机与相册权限，ExtAPI 也不能引用相关 API，
# 否则上架上传会报 ITMS-90683（缺少用途说明）。相机能力恢复前这几道闸不要拆。
if /usr/libexec/PlistBuddy -c 'Print :NSCameraUsageDescription' "$IOS_DIR/FocusPlanet/FocusPlanet/Info.plist" >/dev/null 2>&1 || \
   /usr/libexec/PlistBuddy -c 'Print :NSPhotoLibraryUsageDescription' "$IOS_DIR/FocusPlanet/FocusPlanet/Info.plist" >/dev/null 2>&1 || \
   /usr/libexec/PlistBuddy -c 'Print :NSPhotoLibraryAddUsageDescription' "$IOS_DIR/FocusPlanet/FocusPlanet/Info.plist" >/dev/null 2>&1; then
  echo "Camera/photo usage descriptions are back; this release does not support camera or the photo library." >&2
  exit 1
fi
if rg -q 'DCloudPermissionCamera' "$IOS_DIR/FocusPlanet/FocusPlanet.xcodeproj/project.pbxproj"; then
  echo "Host still links DCloudPermissionCamera; remove it for the camera-free build." >&2
  exit 1
fi
extapi_binary="$IOS_DIR/CustomFrameworks/DCloudUTSExtAPI.xcframework/ios-arm64/DCloudUTSExtAPI.framework/DCloudUTSExtAPI"
if [[ -f "$extapi_binary" ]] && nm -u "$extapi_binary" 2>/dev/null | rg -q '_OBJC_CLASS_\$_AVCaptureDevice|_OBJC_CLASS_\$_PHPhotoLibrary|_OBJC_CLASS_\$_UIImagePickerController'; then
  echo "DCloudUTSExtAPI still references camera/photo APIs; trim build-extapi.sh and rebuild." >&2
  exit 1
fi
if rg -q '测试服务|项目真机运行期间' "$IOS_DIR/FocusPlanet/FocusPlanet/Info.plist"; then
  echo "Info.plist still contains test-only copy; ship production wording." >&2
  exit 1
fi

# 上架包内不允许出现测试/联调文案：导出产物会整包进 App，构后不便再改，这里在打包前拦。
# 本地测试模式（LOCAL_TEST_MODE=true）下这些文案本来就在产物里，调试时允许；
# 发布闸由 archive.sh 守住（开关未关就拒绝出包），所以这里只在发布配置下检查。
bundle_dir="$IOS_DIR/FocusPlanet/FocusPlanet/uni-app-x/apps/$APP_ID"
test_copy_pattern='本地验证码|仅测试阶段|本地测试登录|测试服务|项目真机运行期间|临时测试'
if grep -q 'export const LOCAL_TEST_MODE = false' "$PROJECT_ROOT/utils/local-test.uts" && rg -q --no-messages "$test_copy_pattern" "$bundle_dir"; then
  echo "Test-only copy found in the exported app bundle; remove it from the sources and re-run prepare-xcode.sh." >&2
  rg -n --no-messages "$test_copy_pattern" "$bundle_dir" | head -5 >&2
  exit 1
fi

if nm -gj "$plugin_framework/ios-arm64/unimoduleFocusFaceDetector.framework/unimoduleFocusFaceDetector" | rg -q 'OBJC_CLASS_\$_(UTSOC|DCloudUTSConfig)'; then
  echo "The face detector contains duplicate UTS bootstrap classes; rebuild it without UTSOC.mm." >&2
  exit 1
fi
# 首页渐变已改为静态 SVG，不再要求原生渐变类；端侧检测仍保留完整校验。

plist_appid="$(/usr/libexec/PlistBuddy -c 'Print :uniapp-x:appid' "$IOS_DIR/FocusPlanet/FocusPlanet/Info.plist")"
[[ "$plist_appid" == "$APP_ID" ]] || { echo "Info.plist appid mismatch: $plist_appid" >&2; exit 1; }

"$SCRIPT_DIR/check-resource-freshness.sh"
xcodebuild -list -project "$IOS_DIR/FocusPlanet/FocusPlanet.xcodeproj" >/dev/null
echo "Xcode local-packaging inputs are ready."
